#!/usr/bin/env node
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const source = readFileSync(new URL("../lib/client.js", import.meta.url), "utf8");
const start = source.indexOf('    var DRAFT_KEY =');
const end = source.indexOf('    function ViewerShell()', start);
assert(start > 0 && end > start);
const data = new Map();
const sandbox = { Blob, Date, Number, window: { localStorage: { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) } } };
vm.createContext(sandbox); vm.runInContext(source.slice(start, end) + ';globalThis.api={readDrafts,storeDraft,mergeCanvasDoc};', sandbox);
const { readDrafts, storeDraft, mergeCanvasDoc } = sandbox.api;
const initial = { path: '/report.canvas.tsx', source: 'old', revision: 'r1' };
let tab = mergeCanvasDoc(null, initial); assert.equal(tab.baseRevision, 'r1'); assert.equal(tab.dirty, false);
tab = { ...tab, editor: 'draft', dirty: true };
let merged = mergeCanvasDoc(tab, { ...initial, source: 'external', revision: 'r2' });
assert.equal(merged.editor, 'draft'); assert.equal(merged.baseRevision, 'r1'); assert.equal(merged.source, 'external'); assert.equal(merged.conflict, true);
let saved = mergeCanvasDoc(tab, { ...initial, source: 'draft', revision: 'r3' }, 'draft');
assert.equal(saved.dirty, false); assert.equal(saved.editor, null); assert.equal(saved.baseRevision, 'r3');
let typing = mergeCanvasDoc({ ...tab, editor: 'newer' }, { ...initial, source: 'draft', revision: 'r3' }, 'draft');
const reverted = mergeCanvasDoc({ ...tab, editor: 'old', dirty: false, savePending: true }, { ...initial, source: 'draft', revision: 'r3' }, 'draft');
assert.equal(reverted.editor, 'old'); assert.equal(reverted.dirty, true);
const pushed = mergeCanvasDoc({ ...tab, editor: 'old', dirty: false, savePending: true }, { ...initial, source: 'draft', revision: 'r3' });
assert.equal(pushed.editor, 'old'); assert.equal(pushed.dirty, true);
assert.equal(typing.editor, 'newer'); assert.equal(typing.dirty, true); assert.equal(typing.baseRevision, 'r3'); assert.equal(typing.conflict, false);
assert(storeDraft({...tab,dirty:false,savePending:true,editor:"old"},false)); assert.equal(readDrafts()[0].editor,"old");
assert(storeDraft(tab, false)); assert.equal(readDrafts()[0].editor, 'draft');
assert(storeDraft(tab, true)); assert.equal(readDrafts().length, 0);
for(let i=0;i<12;i++) storeDraft({ ...tab, path: String(i) }, false);
assert.equal(readDrafts().length, 10);
data.set('dsh-cv-drafts-v1', '{bad json'); assert.equal(readDrafts().length, 0);
data.set('dsh-cv-drafts-v1', JSON.stringify([{path:'old',editor:'x',baseSource:'',baseRevision:'r',updatedAt:Date.now()-8*86400000}])); assert.equal(readDrafts().length, 0);
assert.equal(storeDraft({...tab,editor:'a'.repeat(1024*1024)},false),false);
console.log('editor-state: base revisions, dirty reloads, in-flight typing, bounded recovery and expiry passed');
